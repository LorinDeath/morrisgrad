// Туман войны: кодек RLE, открытие круга, хранилище (без D1 — в памяти), раздельные герои, реестр объектов карты.
import { FOG_N, FOG_CELL, newMask, reveal, encodeMask, decodeMask, countBits, getBit } from "./explore";
import { ExploreStore } from "./exploreDb";
import { markersOf, registerMarker, unregisterMarker, onMarkers } from "./markers";
let pass = 0, fail = 0; const ok = (c: any, m: string) => { c ? pass++ : fail++; console.log((c ? "PASS " : "FAIL ") + m); };
const m = newMask();
ok(encodeMask(m).length < 16, `пустая маска сжата: ${encodeMask(m).length} символов`);
const a = reveal(m, 24000, 24000);
ok(a.length > 100 && a.length < 200, `круг R=7 открывает ${a.length} ячеек`);
ok(reveal(m, 24000, 24000).length === 0, "повторное открытие — ничего нового");
const ci = Math.floor(24000 / FOG_CELL); ok(getBit(m, ci * FOG_N + ci) === 1, "центральная ячейка открыта");
ok(reveal(m, -500, -500).length === 0 || true, "за краем — без исключений");
for (let x = 1000; x < 47000; x += 600) reveal(m, x, 30000 + Math.sin(x / 3000) * 4000);
const enc = encodeMask(m), dec = decodeMask(enc);
ok(countBits(dec) === countBits(m) && dec.every((v, i) => v === m[i]), `кодек туда-обратно (${countBits(m)} ячеек → ${enc.length} байт base64)`);
ok(enc.length < 4000, "маска пути компактна (<4 КБ)");
ok(countBits(decodeMask("мусор!!")) === 0 && countBits(decodeMask(null)) === 0, "битые данные → пустая маска");
const st = new ExploreStore(null);
st.visit("acc1", "mage", "arinar", 24000, 24000); st.visit("acc1", "mage", "arinar", 25000, 24000);
ok(st.takePending("acc1", "mage", "arinar").length > 150, "pend копит новые ячейки");
ok(st.takePending("acc1", "mage", "arinar").length === 0, "pend очищается");
st.visit("acc1", "mage", "hellfire", 500, 500); ok(!st.map.has("acc1|mage|hellfire"), "в Поляне тумана нет");
await Promise.resolve();
const f1 = await st.full("acc1", "mage", "arinar");
await st.flushKey("acc1"); ok(!st.map.size && st.mem.size === 1, "flush сохраняет и выгружает");
const f2 = await st.full("acc1", "mage", "arinar"); ok(f2.cells === f1.cells && f2.cells > 150, `после перезахода маска та же (${f2.cells})`);
const f3 = await st.full("acc1", "warrior", "arinar"); ok(f3.cells === 0, "другой герой — карта с нуля");
ok(markersOf("arinar", "sign").length >= 40, `таблички в реестре: ${markersOf("arinar", "sign").length}`);
ok(markersOf("arinar", "portal").length >= 1 && markersOf("arinar", "boss").length >= 32, "порталы и логова боссов в реестре");
let ev = 0; const off = onMarkers(() => ev++);
registerMarker({ id: "t1", type: "chest", x: 100, y: 100, icon: "📦", label: "Тест", world: "arinar" });
ok(markersOf("arinar", "chest").length === 1 && ev === 1, "новый тип объекта регистрируется и оповещает");
unregisterMarker("t1"); ok(markersOf("arinar", "chest").length === 0, "снятие с реестра"); off?.();
console.log(`\n${pass}/${pass + fail} passed`); if (fail) process.exit(1);
