export const GUEST_PREFIX = "«Гость» ";
export const guestDisplay = (n: string) => GUEST_PREFIX + n;
export const isGuestName = (n: string) => GUEST_NAMES.includes(n);
// стабильный «по умолчанию» выбор по ключу профиля (FNV-1a) — для профилей, у которых имя ещё не записано
export function guestNameFor(pkey: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < pkey.length; i++) h = Math.imul(h ^ pkey.charCodeAt(i), 16777619);
  return GUEST_NAMES[(h >>> 0) % GUEST_NAMES.length];
}
