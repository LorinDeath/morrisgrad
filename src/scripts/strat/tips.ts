function fallback(e: HTMLElement): string | null {
  const t = e.getAttribute("title"); if (t) { e.removeAttribute("title"); return t; }
  const a = e.getAttribute("aria-label") || (e as HTMLInputElement).placeholder; if (a) return a;
  const x = txt(e); return x && x.length < 60 ? x : null;
}
const INTER = "button,select,input:not([type=hidden]),textarea,a[href],[role=button],summary";
export function applyTips(root: ParentNode = document) {
  for (const [sel, t] of TIPS) root.querySelectorAll<HTMLElement>(sel).forEach((e) => {
    if (e.dataset.tip || e.dataset.pas || e.closest("[data-tip]:not(label.fld),[data-pas]")) return; const v = typeof t === "string" ? t : t(e); if (v) e.dataset.tip = v; });
  root.querySelectorAll<HTMLElement>(INTER).forEach((e) => { if (e.dataset.tip || e.closest("[data-tip],[data-pas],[data-notip],#tip")) return;
    // подпись поля ввода — подсказка всей строки
    const v = fallback(e) || (e.closest("label")?.textContent || "").replace(/\s+/g, " ").trim().slice(0, 80); if (v) e.dataset.tip = v; });
}
let qd = false;
export function watchTips() {
  applyTips(); new MutationObserver(() => { if (qd) return; qd = true; requestAnimationFrame(() => { qd = false; applyTips(); }); }).observe(document.body, { childList: true, subtree: true });
}
