def spoiler_of(label):
    """Самая поздняя книга/глава из метки. Будущие главы — план, сам не открывается."""
    low = label.lower()
    if "будущие главы" in low: return ("book:darg-sirrom", 99, "авторский план будущих глав «Дарг Сиррома»")
    if "дарг сирром" in low: return ("book:darg-sirrom", 1, "«Дарг Сирром», глава 1")
    if "праведные коты" in low: return ("book:pravednye-koty", 1, "«Праведные коты»")
    best = 0
    for k, v in OB.items():
        if k in low: best = max(best, v)
    if best == 23: return ("book:obitel-smerti", 23, "летопись, История третья")
    return ("book:obitel-smerti", best or 1, "летопись, " + label.replace("Летопись, ", ""))
def sent_cut(text):
    parts = re.split(r"(?<=[.!?…])\s+", text)
    parts = [x for x in parts if not re.match(r"^Раскрывать постепенно", x)]  # служебная пометка автора, не лор
    kept = [x for x in parts if not HIDDEN.search(x)]
    return " ".join(kept).strip(), len(kept) != len(parts)
